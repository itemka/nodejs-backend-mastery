import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

import * as ui from '@workspaces/cli-output';

const SOURCE_PATH = '.mcp.json';
const TARGET_PATH = '.codex/config.toml';
const ENABLED_PATH = '.codex/mcp-enabled.json';
const BEGIN_MARKER = '# BEGIN generated by pnpm sync-mcp';
const END_MARKER = '# END generated by pnpm sync-mcp';
const MCP_TABLE_PATTERN = /^\s*\[mcp_servers(?:\]|\.)/m;
const HELP_FLAGS = new Set(['--help', '-h']);
const ENV_REFERENCE_PATTERN = /^\$\{([A-Za-z_][A-Za-z0-9_]*)\}$/;
const BEARER_REFERENCE_PATTERN = /^Bearer \$\{([A-Za-z_][A-Za-z0-9_]*)\}$/i;
// Matched against whole name segments, so MAX_TOKENS and AUTHOR_NAME stay static
// while GITHUB_TOKEN, X-API-Key, apiKey, and PRIVATE_KEY still require a reference.
// The plural "tokens" is deliberately absent: it names LLM limits far more often
// than secrets.
const CREDENTIAL_WORDS = new Set([
  'apikey',
  'auth',
  'authorization',
  'cookie',
  'credential',
  'credentials',
  'passwd',
  'password',
  'privatekey',
  'secret',
  'secrets',
  'token',
]);
const CREDENTIAL_WORD_PAIRS = [
  ['api', 'key'],
  ['access', 'key'],
  ['private', 'key'],
];
const URL_PATTERN = /https?:\/\/[^\s"'<>]+/gi;
// Any scheme with an authority, so redis://:secret@host is parsed like an HTTP URL.
const ANY_URL_PATTERN = /\b[a-z][a-z0-9+.-]*:\/\/[^\s"'<>]+/gi;
const argv = process.argv.slice(2);
const check = argv.includes('--check');
const staged = argv.includes('--staged');
const HELP_TEXT = `
Usage:
  pnpm sync-mcp
  pnpm sync-mcp --check
  pnpm sync-mcp --check --staged
  node scripts/sync-mcp-to-codex.mjs --help

Reads the shared ${SOURCE_PATH} file and writes MCP server entries into ${TARGET_PATH}.
When ${ENABLED_PATH} exists, only the listed servers are written.
--check reports stale output without writing. --staged checks the Git index.

Requirements:
  - ${SOURCE_PATH} must exist in the repo root.
  - ${SOURCE_PATH} must contain a top-level "mcpServers" object.
  - ${ENABLED_PATH}, when present, must contain "enabledMcpServers" or
    "enabledMcpjsonServers" as an array of server names.

Notes:
  - Shared configs contain references, never credentials. Keep values in private .mcp.env.
  - Generation never reads .mcp.env or resolves environment variables.
  - ${ENABLED_PATH} is the Codex allowlist; all source servers are validated.
  - Exact env references such as "TOKEN": "\${TOKEN}" become Codex env_vars entries.
    References cannot rename variables; the env key and referenced variable must match.
  - Authorization: "Bearer \${TOKEN}" becomes bearer_token_env_var = "TOKEN".
  - Whole-value header references become env_http_headers entries.
  - Other embedded references, defaults, and references in command/args/url are rejected.
  - env is stdio-only; Codex rejects env and env_vars on url servers.
  - Existing generated output is replaced between ${BEGIN_MARKER} and ${END_MARKER}.
  - Existing non-MCP Codex settings are preserved.
`.trim();

class ConfigError extends Error {
  name = 'ConfigError';
}

const fail = (message) => {
  throw new ConfigError(message);
};

const isObject = (value) => value && typeof value === 'object' && !Array.isArray(value);
// The MCP fields this script emits are string-oriented. Use a typed TOML writer if
// this script later grows numeric, boolean, or mixed-type config output.
const tomlString = (value) => JSON.stringify(String(value));
const tomlKey = (name) => (/[^a-zA-Z0-9_-]/.test(name) ? tomlString(name) : name);
const isEnoent = (error) => isObject(error) && error.code === 'ENOENT';

const isCredentialName = (name) => {
  const words = name
    .replaceAll(/([a-z0-9])([A-Z])/g, '$1 $2')
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter(Boolean);
  return (
    words.some((word) => CREDENTIAL_WORDS.has(word)) ||
    CREDENTIAL_WORD_PAIRS.some(([first, second]) =>
      words.some((word, index) => word === first && words[index + 1] === second),
    )
  );
};

const readConfigText = (path) => {
  if (staged) {
    try {
      return execFileSync('git', ['show', `:${path}`], { encoding: 'utf8', stdio: 'pipe' });
    } catch {
      return;
    }
  }
  try {
    return readFileSync(path, 'utf8');
  } catch (error) {
    if (isEnoent(error)) return;
    fail(`Could not read ${path}.`);
  }
};

// `fail` throws today, but the explicit `return` after each call keeps control
// flow obvious if `fail`'s signature is ever loosened.
const readJsonFile = (path, missingMessage) => {
  const content = readConfigText(path);
  if (content === undefined) {
    fail(missingMessage);
    return;
  }

  let parsed;
  try {
    parsed = JSON.parse(content);
  } catch {
    // JSON parser errors can include source excerpts containing credentials.
    fail(`Could not parse ${path}: invalid JSON.`);
    return;
  }

  // Reject `null`, primitives, and other non-container JSON so callers can
  // safely dereference the result with a typed ConfigError instead of a raw
  // "Cannot read properties of null" runtime crash.
  if (parsed === null || typeof parsed !== 'object') {
    fail(`${path} must contain a JSON object or array.`);
    return;
  }

  return parsed;
};

const readMcpServers = () => {
  const parsed = readJsonFile(
    SOURCE_PATH,
    `Missing ${SOURCE_PATH}${staged ? ' in the Git index' : ''}. Restore the shared MCP config.`,
  );

  if (!isObject(parsed.mcpServers)) {
    fail(`${SOURCE_PATH} must contain an object at "mcpServers".`);
  }

  return parsed.mcpServers;
};

const readEnabledServerNames = (mcpServers) => {
  if (readConfigText(ENABLED_PATH) === undefined) return null;

  const parsed = readJsonFile(ENABLED_PATH, `Missing ${ENABLED_PATH}.`);
  const enabled = Array.isArray(parsed)
    ? parsed
    : (parsed.enabledMcpServers ?? parsed.enabledMcpjsonServers);

  if (!Array.isArray(enabled)) {
    fail(
      `${ENABLED_PATH} must be an array or contain "enabledMcpServers" / "enabledMcpjsonServers" as an array.`,
    );
  }

  const invalidNames = enabled.filter((name) => typeof name !== 'string' || !name.trim());
  if (invalidNames.length > 0) {
    fail(`${ENABLED_PATH} enabled server names must be non-empty strings.`);
  }

  const names = [...new Set(enabled)];
  const missingNames = names.filter((name) => !Object.hasOwn(mcpServers, name));
  if (missingNames.length > 0) {
    fail(`${ENABLED_PATH} references unknown MCP servers: ${missingNames.join(', ')}`);
  }

  return new Set(names);
};

const filterEnabledMcpServers = (mcpServers, enabledServerNames) => {
  if (!enabledServerNames) return mcpServers;

  return Object.fromEntries(
    Object.entries(mcpServers).filter(([serverName]) => enabledServerNames.has(serverName)),
  );
};

const assertStaticValue = (value, location) => {
  if (typeof value !== 'string') fail(`${location} must be a string.`);
  if (value.includes('${')) {
    fail(
      `${location} contains an unsupported environment reference. Use env_vars or an HTTP header reference.`,
    );
  }
  if (
    /\b(?:github_pat_[\w]+|gh[pousr]_[\w]+|sk-(?:proj-|ant-)?[\w-]{20,})|-----BEGIN (?:[A-Z0-9]+ )*PRIVATE KEY-----/.test(
      value,
    )
  ) {
    fail(`${location} contains a credential. Use an environment reference.`);
  }
  // HTTP(S) URLs are checked below; their paths (https://host/home/...) are not local paths.
  if (
    /(?:\/Users\/|\/home\/|\/root\/|[A-Za-z]:\\Users\\)/.test(value.replaceAll(URL_PATTERN, ''))
  ) {
    fail(
      `${location} contains a personal path. Keep machine-specific servers in local configuration.`,
    );
  }
  if (/\b(?:postgres(?:ql)?|mysql|mariadb|mongodb(?:\+srv)?|rediss?):\/\//i.test(value)) {
    fail(`${location} contains a database URL. Keep database servers in local configuration.`);
  }
  // Parse each embedded URL on its own so "--registry=https://..." is accepted.
  for (const [candidate] of value.matchAll(ANY_URL_PATTERN)) {
    let url;
    try {
      url = new URL(candidate);
    } catch {
      fail(`${location} contains an invalid URL.`);
    }
    if (
      url.username ||
      url.password ||
      [...url.searchParams.keys()].some((key) => isCredentialName(key))
    ) {
      fail(
        `${location} contains URL credentials. Use an HTTP header reference or private local configuration.`,
      );
    }
  }
};

const assertArguments = (args, serverName) => {
  const location = `Server "${serverName}" args`;
  for (const argument of args) {
    assertStaticValue(argument, location);
    // Inspect option names separately from their opaque values. This covers
    // both --api-key=value and --api-key value without printing either value.
    const option = /^--?([^=\s]+)(?:[=\s]|$)/.exec(argument);
    const header = /(?:^|[=\s])([\w-]+)\s*:/.exec(argument.replace(/^-H(?=[A-Za-z])/, ''));
    if ((option && isCredentialName(option[1])) || (header && isCredentialName(header[1]))) {
      fail(
        `${location} contains a credential option or header. Use environment-based authentication or private local configuration.`,
      );
    }
  }
};

const buildObjectEntriesToml = (prefix, value, serverName) => {
  if (!isObject(value)) fail(`Server "${serverName}" ${prefix} must be an object.`);

  return Object.entries(value).map(([key, entryValue]) => {
    assertStaticValue(entryValue, `Server "${serverName}" ${prefix} "${key}"`);
    if (isCredentialName(key))
      fail(`Server "${serverName}" ${prefix} "${key}" must use an environment reference.`);
    return `${prefix}.${tomlKey(key)} = ${tomlString(entryValue)}`;
  });
};

const buildHeadersToml = (headers, serverName) => {
  if (!isObject(headers)) fail(`Server "${serverName}" headers must be an object.`);
  const names = new Set();
  return Object.entries(headers).map(([name, value]) => {
    const normalized = name.toLowerCase();
    if (names.has(normalized)) fail(`Server "${serverName}" has duplicate header "${name}".`);
    names.add(normalized);
    if (typeof value !== 'string')
      fail(`Server "${serverName}" header "${name}" must be a string.`);
    const bearer = normalized === 'authorization' && BEARER_REFERENCE_PATTERN.exec(value);
    if (bearer) return `bearer_token_env_var = ${tomlString(bearer[1])}`;
    const reference = ENV_REFERENCE_PATTERN.exec(value);
    if (reference) return `env_http_headers.${tomlKey(name)} = ${tomlString(reference[1])}`;
    return buildObjectEntriesToml('http_headers', { [name]: value }, serverName)[0];
  });
};

const splitEnvironmentEntries = (env, serverName) => {
  if (!isObject(env)) fail(`Server "${serverName}" env must be an object.`);

  const forwarded = [];
  const staticEntries = {};

  for (const [key, value] of Object.entries(env)) {
    const match = typeof value === 'string' ? ENV_REFERENCE_PATTERN.exec(value) : null;
    if (!match) {
      staticEntries[key] = value;
      continue;
    }

    const [, sourceName] = match;
    if (sourceName !== key) {
      fail(
        `Server "${serverName}" env "${key}" references "${sourceName}", but Codex env_vars cannot rename variables. Use the same name on both sides.`,
      );
    }

    forwarded.push(key);
  }

  return { forwarded, staticEntries };
};

const buildServerToml = ([serverName, cfg]) => {
  if (!isObject(cfg)) fail(`Server "${serverName}" must be an object.`);
  const supported = new Set(['_description', 'type', 'command', 'args', 'url', 'headers', 'env']);
  for (const key of Object.keys(cfg)) {
    if (!supported.has(key)) fail(`Server "${serverName}" has unsupported field "${key}".`);
  }
  if (cfg.command && cfg.url) fail(`Server "${serverName}" cannot define both command and url.`);
  if (!cfg.command && !cfg.url) fail(`Server "${serverName}" must define command or url.`);
  // Claude Code skips a url entry without a type, so the shared source must declare it.
  if (cfg.url ? cfg.type !== 'http' : cfg.type !== undefined && cfg.type !== 'stdio') {
    fail(
      `Server "${serverName}" type must be "http" for a url server, or "stdio" or omitted for a command server.`,
    );
  }
  if (cfg.args && !Array.isArray(cfg.args)) fail(`Server "${serverName}" args must be an array.`);
  // Codex rejects env and env_vars on streamable HTTP servers, so emitting them
  // would produce a config.toml it refuses to load.
  if (cfg.url && cfg.env) {
    fail(
      `Server "${serverName}" cannot define env with url. Codex allows env only on stdio servers; move the value into headers.`,
    );
  }
  if (cfg.url && cfg.args) fail(`Server "${serverName}" cannot define args with url.`);
  if (cfg.command && cfg.headers) fail(`Server "${serverName}" headers are HTTP-only.`);

  const lines = [`[mcp_servers.${tomlKey(serverName)}]`];

  if (cfg.command) {
    assertStaticValue(cfg.command, `Server "${serverName}" command`);
    lines.push(`command = ${tomlString(cfg.command)}`);
  }
  if (cfg.args) {
    assertArguments(cfg.args, serverName);
    lines.push(`args = [${cfg.args.map((argument) => tomlString(argument)).join(', ')}]`);
  }
  if (cfg.url) {
    assertStaticValue(cfg.url, `Server "${serverName}" url`);
    if (!/^https?:\/\//.test(cfg.url)) fail(`Server "${serverName}" url must use HTTP or HTTPS.`);
    lines.push(`url = ${tomlString(cfg.url)}`);
  }
  if (cfg.headers) lines.push(...buildHeadersToml(cfg.headers, serverName));
  if (cfg.env) {
    const { forwarded, staticEntries } = splitEnvironmentEntries(cfg.env, serverName);
    if (forwarded.length > 0) {
      lines.push(`env_vars = [${forwarded.map((entry) => tomlString(entry)).join(', ')}]`);
    }
    lines.push(...buildObjectEntriesToml('env', staticEntries, serverName));
  }

  return `${lines.join('\n')}\n`;
};

const buildGeneratedBlock = (mcpServers) =>
  [
    BEGIN_MARKER,
    `# Source: ${SOURCE_PATH}. Do not edit this block by hand.`,
    '[mcp_servers]',
    '',
    ...Object.entries(mcpServers).map((entry) => buildServerToml(entry)),
    END_MARKER,
    '',
  ].join('\n');

const isOnlyMcpConfig = (currentConfig) => {
  let inMcpTable = false;

  for (const line of currentConfig.split(/\r?\n/)) {
    const trimmedLine = line.trim();
    if (!trimmedLine || trimmedLine.startsWith('#')) continue;

    if (trimmedLine.startsWith('[')) {
      inMcpTable = MCP_TABLE_PATTERN.test(trimmedLine);
      if (!inMcpTable) return false;
      continue;
    }

    if (!inMcpTable) return false;
  }

  return true;
};

const replaceGeneratedBlock = (currentConfig, generatedBlock) => {
  const hasBegin = currentConfig.includes(BEGIN_MARKER);
  const hasEnd = currentConfig.includes(END_MARKER);

  if (hasBegin !== hasEnd) {
    fail(`${TARGET_PATH} has an incomplete pnpm sync-mcp generated block.`);
  }

  if (hasBegin) {
    const blockPattern = new RegExp(String.raw`${BEGIN_MARKER}[\s\S]*?${END_MARKER}\n?`);
    const outside = currentConfig.replace(blockPattern, '');
    if (
      outside.includes(BEGIN_MARKER) ||
      outside.includes(END_MARKER) ||
      MCP_TABLE_PATTERN.test(outside)
    ) {
      fail(`${TARGET_PATH} contains MCP entries outside its single generated block.`);
    }
    return currentConfig.replace(blockPattern, generatedBlock);
  }

  if (!currentConfig.trim()) return generatedBlock;
  if (MCP_TABLE_PATTERN.test(currentConfig) && isOnlyMcpConfig(currentConfig))
    return generatedBlock;

  if (MCP_TABLE_PATTERN.test(currentConfig)) {
    fail(
      `${TARGET_PATH} already contains MCP server config without pnpm sync-mcp markers. Move manual MCP entries into ${SOURCE_PATH}, remove the old MCP block, or add generated markers before rerunning.`,
    );
  }

  return `${currentConfig.replace(/\s*$/, '')}\n\n${generatedBlock}`;
};

const writeCodexConfig = (generatedBlock) => {
  const currentConfig = readConfigText(TARGET_PATH) ?? '';
  const nextConfig = replaceGeneratedBlock(currentConfig, generatedBlock);

  if (check) {
    if (currentConfig !== nextConfig) {
      fail(
        `${TARGET_PATH}${staged ? ' in the Git index' : ''} is stale or missing. Run pnpm sync-mcp${staged ? ' and stage the source, allowlist, and output together' : ''}.`,
      );
    }
    return;
  }
  mkdirSync('.codex', { recursive: true });
  if (currentConfig !== nextConfig) writeFileSync(TARGET_PATH, nextConfig);
};

if (argv.some((argument) => HELP_FLAGS.has(argument))) {
  console.log(HELP_TEXT);
} else {
  try {
    if (argv.some((argument) => !['--check', '--staged'].includes(argument)))
      fail('Unsupported option. Use --help for usage.');
    if (staged && !check)
      fail('--staged requires --check. Generation never modifies the Git index.');
    const mcpServers = readMcpServers();
    const enabledServerNames = readEnabledServerNames(mcpServers);
    // The source itself is committed, including entries excluded from Codex.
    for (const entry of Object.entries(mcpServers)) buildServerToml(entry);
    writeCodexConfig(buildGeneratedBlock(filterEnabledMcpServers(mcpServers, enabledServerNames)));
    console.log(
      ui.success(
        check
          ? `MCP config is current${staged ? ' in the Git index' : ''}.`
          : `Synced ${SOURCE_PATH} to ${ui.muted(TARGET_PATH)}`,
      ),
    );
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.error(ui.error(`sync-mcp failed: ${message}`));
    process.exitCode = 1;
  }
}
